/* The hello example in C (uniapi.h): the page calls a C function, and C calls a JavaScript
 * function. It shows the same page as examples/hello, compiled into the program. */

#include <uniapi/uniapi.h>

#include <stdio.h>
#include <time.h>

UNIAPI_C_ASSETS(hello_c_web); /* generated by uniapi_embed() in CMakeLists.txt */

static uniapi_app* app;
static time_t start;

/* JavaScript -> C: the page runs  await app.native.greet("Ada") */
static void greet(void* user, const char* args_json, const uniapi_bytes* bytes, uniapi_reply* reply) {
    char* name = uniapi_json_get_string(args_json, "/0");
    (void)user;
    (void)bytes;
    if (!name || !*name) {
        uniapi_reply_reject(reply, "Type a name first.");
    } else {
        char text[512];
        char* json;
        snprintf(text, sizeof text, "Hello, %s! This answer came from C.", name);
        json = uniapi_json_string(text); /* a JSON string literal, quotes escaped */
        uniapi_reply_resolve(reply, json);
        uniapi_free(json);
    }
    uniapi_free(name);
}

/* C -> JavaScript: once a second, call the page's showUptime(). */
static void tick(void* user) {
    char args[32];
    (void)user;
    if (!uniapi_connected(app)) return;
    snprintf(args, sizeof args, "[%.0f]", difftime(time(NULL), start));
    uniapi_call(app, "showUptime", args, NULL, NULL);
}

int main(void) {
    uniapi_options options;
    int code;
    uniapi_options_init(&options);
    options.title = "Hello uniapi (C)";
    options.width = 560;
    options.height = 360;
    app = uniapi_app_new(&options);
    if (!app) {
        fprintf(stderr, "hello_c: %s\n", uniapi_last_error());
        return 1;
    }
    start = time(NULL);
    uniapi_serve(app, uniapi_assets_hello_c_web());
    uniapi_expose(app, "greet", greet, NULL);
    uniapi_every(app, 1000, tick, NULL);
    uniapi_navigate(app, "/index.html");
    code = uniapi_run(app);
    uniapi_app_free(app);
    return code;
}
