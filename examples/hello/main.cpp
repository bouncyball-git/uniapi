// The smallest useful uniapi app: the page calls a C++ function, and C++ calls a
// JavaScript function. The page is web/index.html, compiled into the program.

#include <uniapi/uniapi.hpp>

#include <chrono>
#include <stdexcept>
#include <string>

UNIAPI_ASSETS(hello_web);  // generated by uniapi_embed() in CMakeLists.txt

int main() {
    uniapi::AppOptions options;
    options.title = "Hello uniapi";
    options.width = 560;
    options.height = 360;
    uniapi::App app(options);
    app.serve(hello_web);

    // JavaScript -> C++: the page runs  await app.native.greet("Ada")
    app.expose("greet", [](const std::string& name) {
        if (name.empty()) throw std::invalid_argument("Type a name first.");
        return "Hello, " + name + "! This answer came from C++.";
    });

    // C++ -> JavaScript: once a second, call the page's showUptime().
    const auto start = std::chrono::steady_clock::now();
    app.every(std::chrono::seconds(1), [&] {
        if (!app.connected()) return;
        const auto seconds = std::chrono::duration_cast<std::chrono::seconds>(
            std::chrono::steady_clock::now() - start).count();
        app.call("showUptime", uniapi::json::array({seconds}));
    });

    app.navigate("/index.html");
    return app.run();
}
