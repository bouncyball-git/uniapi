#pragma once

#include <cstddef>
#include <string_view>

namespace uniapi {

// A file compiled into the program by the uniapi_embed() CMake function.
struct Asset {
    const char* path;  // relative to the embedded directory, e.g. "index.html" or "css/app.css"
    const unsigned char* data;
    size_t size;            // the file's size in bytes
    size_t packedSize = 0;  // 0: `data` is the file. Otherwise uniapi_embed() compressed it:
                            // `data` holds packedSize bytes of zlib; read it with assetData()
};

// A file's bytes, uncompressed.
struct AssetData {
    const unsigned char* data;
    size_t size;
};

// The bytes of an embedded file: `data` itself, or, for a file uniapi_embed() compressed
// (COMPRESS), the file inflated on first use and kept for the life of the program, so the
// pointer stays good. {nullptr, 0} if it can't be inflated (a damaged build). Safe from any
// thread. (Serving a page does not go through this: it inflates for the request and keeps
// nothing.)
AssetData assetData(const Asset& asset);

struct AssetTable {
    const Asset* items;
    size_t count;

    // The file at `path` (e.g. "img/icon.png"), or nullptr.
    const Asset* find(std::string_view path) const {
        for (size_t i = 0; i < count; ++i) {
            if (path == items[i].path) return &items[i];
        }
        return nullptr;
    }
};

}  // namespace uniapi

// Declares a table generated by uniapi_embed(<target> <name> <directory>), e.g.
//   UNIAPI_ASSETS(demo_web);
//   app.serve(demo_web);
#define UNIAPI_ASSETS(name) extern const ::uniapi::AssetTable name
